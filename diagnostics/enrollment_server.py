from leaderboard.store import token_digest as legacy_token_digest, utc_now
from .protocol import DiagnosticError, canonical_bytes, decode_json, exact_object, require

DEVICE_PATTERN = re.compile(r"apd_[A-Za-z0-9_-]{43}\Z")
MAX_BODY_BYTES = 4096
PASSWORD_SCHEME = "scrypt-n32768-r8-p1-v1"
MAX_TEAMS = 5000
MAX_DEVICES_PER_TEAM = 32
MAX_KDF_CONCURRENCY = 2
CLASSROOM_DASHBOARD = Path(__file__).resolve().parent / "assets/classroom_dashboard.html"
SCRYPT_N = 32768
SCRYPT_R = 8
SCRYPT_P = 1


def team_name(value):
    require(type(value) is str and 1 <= len(value) <= 240 and value.isprintable(),
            "INVALID_TEAM_NAME", "Use a team name of 1 to 60 printable characters.")
    display = " ".join(unicodedata.normalize("NFKC", value).split())
    require(1 <= len(display) <= 60 and display.isprintable(),
            "INVALID_TEAM_NAME", "Use a team name of 1 to 60 printable characters.")
    return display.casefold(), display


def password_bytes(value):
    require(type(value) is str and len(value) >= 12 and value.isprintable() and bool(value.strip()),
            "INVALID_TEAM_PASSWORD", "Use a shared team password of at least 12 printable characters.")
    try:
        raw = value.encode("utf-8")
    except UnicodeError:
        raise DiagnosticError("INVALID_TEAM_PASSWORD", "Use a valid team password.") from None
    require(len(raw) <= 256, "INVALID_TEAM_PASSWORD", "The team password must fit within 256 UTF-8 bytes.")
    return raw


def checked_device(value):
    require(type(value) is str and DEVICE_PATTERN.fullmatch(value),
            "INVALID_DEVICE_CREDENTIAL", "Use the credential generated by the supplied client.")
    return value


def device_digest(value):
    return hashlib.sha256(b"ap-device-enrollment-v1\0" + checked_device(value).encode("ascii")).hexdigest()


def password_hash(raw, salt):
    return hashlib.scrypt(raw, salt=salt, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P,
                          maxmem=64 * 1024 * 1024, dklen=32)


def parse_origin(value):
    try:
        parts = urlsplit(value)
        require(parts.scheme == "https" and parts.hostname and not parts.username and not parts.password
                and not parts.query and not parts.fragment and parts.path in ("", "/"),
                "ORIGIN_REQUIRED", "Use the configured class origin.", 403)
        return ("https", parts.hostname.lower(), parts.port or 443)
    except (ValueError, TypeError, AttributeError):
        raise DiagnosticError("ORIGIN_REQUIRED", "Use the configured class origin.", 403) from None


class Admission:
    """Bound password CPU/memory before allocating scrypt work."""
    def __init__(self, *, clock=time.monotonic, team_limit=12, source_limit=180,
                 global_limit=240, window_s=60.0, capacity=4096):
        self.clock = clock
        self.team_limit = team_limit
        self.source_limit = source_limit
        self.global_limit = global_limit
        self.window_s = window_s
        self.capacity = capacity
        self._events = {}
        self._guard = threading.Lock()
        self._workers = threading.BoundedSemaphore(MAX_KDF_CONCURRENCY)

    @contextmanager
    def admit(self, name_key, remote_source):
        # Do not trust X-Forwarded-For supplied by an arbitrary caller.
        remote = remote_source if type(remote_source) is str and len(remote_source) <= 128 else "unknown"
        keys = [("team", name_key), ("source", remote), ("global", "")]
        limits = [self.team_limit, self.source_limit, self.global_limit]
        with self._guard:
            now = self.clock()
            cutoff = now - self.window_s
            for key in list(self._events):
                queue = self._events[key]
                while queue and queue[0] <= cutoff:
                    queue.popleft()
                if not queue:
                    del self._events[key]
            require(len(self._events) + sum(key not in self._events for key in keys) <= self.capacity,
                    "ENROLLMENT_RATE_LIMIT", "Enrollment is temporarily busy. Retry shortly.", 429)
            require(all(len(self._events.get(key, ())) < limit for key, limit in zip(keys, limits)),
                    "ENROLLMENT_RATE_LIMIT", "Too many enrollment attempts. Retry after one minute.", 429)
            require(self._workers.acquire(blocking=False), "ENROLLMENT_BUSY",
                    "Enrollment is temporarily busy. Retry shortly.", 429)
            for key in keys:
                self._events.setdefault(key, deque()).append(now)
        try:
            yield
        finally:
            self._workers.release()


class EnrollmentStore:
    def __init__(self, legacy_store, *, key_file=None):
        self.legacy = legacy_store
        self.key_file = (Path(key_file).resolve() if key_file else
                         legacy_store.path.with_name(legacy_store.path.name + ".enrollment.key"))
        require(self.key_file != legacy_store.path, "ENROLLMENT_STORAGE", "Key and database must be separate.")
        with self.legacy.connection() as db:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS enrollment_metadata (
                    name TEXT PRIMARY KEY, value TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS enrollment_teams (
                    name_key TEXT PRIMARY KEY,
                    team_id TEXT NOT NULL UNIQUE REFERENCES teams(team_id),
                    display_name TEXT NOT NULL,
                    password_salt BLOB NOT NULL,
                    password_hash BLOB NOT NULL,
                    password_scheme TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS enrollment_devices (
                    token_digest TEXT PRIMARY KEY,
                    team_id TEXT NOT NULL REFERENCES enrollment_teams(team_id),
                    created_at TEXT NOT NULL,
                    revoked_at TEXT
                );
                CREATE INDEX IF NOT EXISTS enrollment_device_team ON enrollment_devices(team_id);
            """)
            has_state = (db.execute("SELECT 1 FROM enrollment_metadata LIMIT 1").fetchone() is not None
                         or db.execute("SELECT 1 FROM enrollment_teams LIMIT 1").fetchone() is not None)
        self._key = self._load_key(has_state)
        fingerprint = hashlib.sha256(b"ap-enrollment-key-v1\0" + self._key).hexdigest()
        with self.legacy.connection() as db:
            db.execute("BEGIN IMMEDIATE")
            row = db.execute("SELECT value FROM enrollment_metadata WHERE name='key_fingerprint'").fetchone()
            require(row is None or hmac.compare_digest(row["value"], fingerprint),
                    "ENROLLMENT_KEY_MISMATCH", "Restore the matching enrollment key and database backup.")
            db.execute("INSERT OR IGNORE INTO enrollment_metadata VALUES('key_fingerprint',?)", (fingerprint,))
            for row in db.execute("SELECT e.team_id,t.token_digest FROM enrollment_teams e JOIN teams t ON e.team_id=t.team_id"):
                require(hmac.compare_digest(row["token_digest"], legacy_token_digest(self.canonical_token(row["team_id"]))),
                        "ENROLLMENT_KEY_MISMATCH", "Existing team credentials do not match the enrollment key.")
            db.commit()

    def _load_key(self, has_state):
        if not self.key_file.exists():
            require(not has_state, "ENROLLMENT_KEY_MISSING",
                    "Restore the enrollment key from backup. Existing enrollments cannot use a replacement key.")
            self.key_file.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                fd, temporary = tempfile.mkstemp(prefix=".enrollment-key-", dir=self.key_file.parent)
                os.chmod(temporary, 0o600)
                with os.fdopen(fd, "wb") as stream:
                    stream.write(secrets.token_bytes(32))
                    stream.flush()
                    os.fsync(stream.fileno())
                try:
                    os.link(temporary, self.key_file)
                except FileExistsError:
                    pass
            finally:
                if temporary and os.path.exists(temporary):
                    os.unlink(temporary)
        require(self.key_file.is_file() and not self.key_file.is_symlink(),
                "ENROLLMENT_KEY_INVALID", "Enrollment key must be a regular private file.")
        with self.key_file.open("rb") as stream:
            key = stream.read(33)
        require(len(key) == 32, "ENROLLMENT_KEY_INVALID", "Restore the valid enrollment key from backup.")
        return key

    def canonical_token(self, team_id):
        digest = hmac.new(self._key, b"ap-enrollment-team-v1\0" + team_id.encode("ascii"), hashlib.sha256).digest()
        return "aps_" + base64.urlsafe_b64encode(digest).decode("ascii").rstrip("=")

    def connect(self, display, name_key, raw_password, device_token):
        digest = device_digest(device_token)
        identity = "auto_" + hashlib.sha256(name_key.encode("utf-8")).hexdigest()
        # A simultaneous first join may install a different random salt. Reload
        # once and verify its password outside the SQLite write transaction.
        for _ in range(2):
            with self.legacy.connection() as db:
                old = db.execute("SELECT * FROM enrollment_teams WHERE name_key=?", (name_key,)).fetchone()
            salt = old["password_salt"] if old else secrets.token_bytes(16)
            require(old is None or old["password_scheme"] == PASSWORD_SCHEME,
                    "ENROLLMENT_STORAGE", "Unsupported stored password scheme.", 503)
            calculated = password_hash(raw_password, salt)
            with self.legacy.connection() as db:
                db.execute("BEGIN IMMEDIATE")
                current = db.execute("SELECT * FROM enrollment_teams WHERE name_key=?", (name_key,)).fetchone()
                if (old is None) != (current is None) or (old and
                    (old["password_salt"] != current["password_salt"] or old["password_hash"] != current["password_hash"])):
                    db.rollback()
                    continue
                created = current is None
                if current:
                    require(hmac.compare_digest(current["password_hash"], calculated),
                            "TEAM_ACCESS_DENIED", "That team name and password could not be verified.", 401)
                    identity, display = current["team_id"], current["display_name"]
                else:
                    require(db.execute("SELECT COUNT(*) FROM enrollment_teams").fetchone()[0] < MAX_TEAMS,
                            "ENROLLMENT_CAPACITY", "New-team enrollment is temporarily unavailable.", 429)
                    # Legacy teams must never be claimed by choosing their ID
                    # or display name, even when it resembles an automatic ID.
                    for row in db.execute("SELECT team_id,display_name FROM teams"):
                        aliases = {row["team_id"].casefold()}
                        for alias in (row["team_id"], row["display_name"]):
                            try:
                                aliases.add(team_name(alias)[0])
                            except DiagnosticError:
                                pass
                        require(row["team_id"] != identity and name_key not in aliases,
                                "TEAM_ACCESS_DENIED", "That team name and password could not be verified.", 401)
                    now = utc_now()
                    db.execute("INSERT INTO teams VALUES(?,?,?,?,?)",
                               (identity, display, legacy_token_digest(self.canonical_token(identity)), now, now))
                    db.execute("INSERT INTO enrollment_teams VALUES(?,?,?,?,?,?,?)",
                               (name_key, identity, display, salt, calculated, PASSWORD_SCHEME, now))
                master = db.execute("SELECT token_digest FROM teams WHERE team_id=?", (identity,)).fetchone()
                require(master is not None and hmac.compare_digest(master["token_digest"],
                        legacy_token_digest(self.canonical_token(identity))),
                        "ENROLLMENT_KEY_MISMATCH", "Team credentials require instructor recovery.", 503)
                device = db.execute("SELECT team_id,revoked_at FROM enrollment_devices WHERE token_digest=?", (digest,)).fetchone()
                if device:
                    require(device["team_id"] == identity and device["revoked_at"] is None,
                            "DEVICE_UNAUTHORIZED", "This device credential is not available for this team.", 401)
                else:
                    require(db.execute("SELECT COUNT(*) FROM enrollment_devices WHERE team_id=?", (identity,)).fetchone()[0] < MAX_DEVICES_PER_TEAM,
                            "ENROLLMENT_CAPACITY", "This team has reached its device limit.", 429)
                    db.execute("INSERT INTO enrollment_devices VALUES(?,?,?,NULL)", (digest, identity, utc_now()))
                db.commit()
                return {"status": "connected", "team_id": identity, "team_name": display,
                        "created_team": created, "duplicate": device is not None}
        raise DiagnosticError("ENROLLMENT_BUSY", "Enrollment changed concurrently. Retry shortly.", 429)

    def authenticate(self, device_token):
        digest = device_digest(device_token)
        with self.legacy.connection() as db:
            row = db.execute("""
                SELECT e.team_id,e.display_name,d.revoked_at,t.token_digest
                FROM enrollment_devices d JOIN enrollment_teams e ON d.team_id=e.team_id
                JOIN teams t ON e.team_id=t.team_id WHERE d.token_digest=?
            """, (digest,)).fetchone()
        require(row is not None and row["revoked_at"] is None,
                "DEVICE_UNAUTHORIZED", "A connected device is required.", 401)
        canonical = self.canonical_token(row["team_id"])
        require(hmac.compare_digest(row["token_digest"], legacy_token_digest(canonical)),
                "ENROLLMENT_KEY_MISMATCH", "Team credentials require instructor recovery.", 503)
        return {"status": "connected", "team_id": row["team_id"], "team_name": row["display_name"]}, canonical

    def revoke(self, device_token):
        with self.legacy.connection() as db:
            db.execute("UPDATE enrollment_devices SET revoked_at=? WHERE token_digest=?",
                       (utc_now(), device_digest(device_token)))


class EnrollmentApplication:
    def __init__(self, application, *, key_file=None, admission=None):
        self.application = application
        self.leaderboard = application.leaderboard
        self.store = application.store
        self.public_origin = application.public_origin
        self.enrollment = EnrollmentStore(application.leaderboard.store, key_file=key_file)
        self.admission = admission or Admission()

    def __getattr__(self, name):
        return getattr(self.application, name)

    def _origin(self, environ):
        if environ.get("HTTP_ORIGIN"):
            require(parse_origin(environ["HTTP_ORIGIN"]) == self.public_origin,
                    "ORIGIN_REQUIRED", "Use the configured class origin.", 403)

    @staticmethod
    def _bearer(environ):
        value = environ.get("HTTP_AUTHORIZATION", "")
        require(type(value) is str and len(value) <= 512,
                "DEVICE_UNAUTHORIZED", "A connected device is required.", 401)
        parts = value.split()
        require(len(parts) == 2 and parts[0].lower() == "bearer" and DEVICE_PATTERN.fullmatch(parts[1]),
                "DEVICE_UNAUTHORIZED", "A connected device is required.", 401)
        return parts[1]

    @staticmethod
    def _response(start_response, status, value):
        body = canonical_bytes(value)
        headers = [("Content-Type", "application/json; charset=utf-8"), ("Content-Length", str(len(body))),
                   ("Cache-Control", "no-store"), ("X-Content-Type-Options", "nosniff"),
                   ("Referrer-Policy", "no-referrer")]
        if status == 401:
            headers.append(("WWW-Authenticate", 'Bearer realm="Team enrollment"'))
        if status == 429:
            headers.append(("Retry-After", "5"))
        start_response(str(status) + " " + HTTPStatus(status).phrase, headers)
        return [body]

    def __call__(self, environ, start_response):
        path, method = environ.get("PATH_INFO", ""), environ.get("REQUEST_METHOD", "GET")
        if path == "/" and method == "GET" and CLASSROOM_DASHBOARD.is_file():
            body = CLASSROOM_DASHBOARD.read_bytes()
            policy = "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; base-uri 'none'; frame-ancestors 'none'"
            start_response("200 OK", [("Content-Type", "text/html; charset=utf-8"),
                ("Content-Length", str(len(body))), ("Cache-Control", "no-store"),
                ("X-Content-Type-Options", "nosniff"), ("Content-Security-Policy", policy)])
            return [body]
        enrollment_route = path.startswith("/api/enrollment/")
        auth = environ.get("HTTP_AUTHORIZATION", "")
        parts = auth.split() if isinstance(auth, str) and len(auth) <= 4096 else []
        device = parts[1] if len(parts) == 2 and parts[0].lower() == "bearer" and DEVICE_PATTERN.fullmatch(parts[1]) else None
        student_route = (path.startswith("/api/v3/") or path.startswith("/api/diagnostics/")
                         or path == "/api/submissions" or path.startswith("/api/submissions/"))
        if not enrollment_route and not (device and student_route):
            return self.application(environ, start_response)
        try:
            self._origin(environ)
            if enrollment_route:
                require(not environ.get("QUERY_STRING"), "INVALID_QUERY", "Enrollment does not accept URL parameters.")
                if path == "/api/enrollment/connect" and method == "POST":
                    value = self.application._body(environ, MAX_BODY_BYTES)
                    exact_object(value, ("team_name", "password", "device_token"))
                    key, display = team_name(value["team_name"])
                    raw_password = password_bytes(value["password"])
                    checked_device(value["device_token"])
                    with self.admission.admit(key, environ.get("REMOTE_ADDR", "unknown")):
                        answer = self.enrollment.connect(display, key, raw_password, value["device_token"])
                    return self._response(start_response, 200, answer)
                if path == "/api/enrollment/identity" and method == "GET":
                    answer, _ = self.enrollment.authenticate(self._bearer(environ))
                    return self._response(start_response, 200, answer)
                raise DiagnosticError("ENROLLMENT_ENDPOINT", "Unsupported enrollment endpoint or method.", 405)
            _, canonical = self.enrollment.authenticate(device)
            translated = dict(environ)
            translated["HTTP_AUTHORIZATION"] = "Bearer " + canonical
            translated["ap.enrollment.device_token"] = device
            return self.application(translated, start_response)
        except DiagnosticError as exc:
            return self._response(start_response, exc.status, {"error": {"code": exc.code, "message": str(exc)}})
        except (OSError, sqlite3.Error, ValueError):
            return self._response(start_response, 503, {"error": {"code": "ENROLLMENT_UNAVAILABLE",
                                    "message": "Team connection is temporarily unavailable. Keep local results and retry."}})
        except Exception:
            return self._response(start_response, 500, {"error": {"code": "ENROLLMENT_INTERNAL",
                                    "message": "Team connection could not be completed. Keep local results and retry."}})

