"""Self-service team enrollment around the unchanged source-matched evaluator.

A shared team password admits a new device. It is never an evaluation input.
Device credentials are hashed. Server-only canonical credentials are derived
from a separate persistent key and never sent to clients. Back up the SQLite
database AND its .enrollment.key file together.
"""
from __future__ import annotations

import base64
from collections import deque
from contextlib import contextmanager
import hashlib
import hmac
from http import HTTPStatus
import os
from pathlib import Path
import re
import secrets
import sqlite3
import tempfile
import threading
import time
import unicodedata
